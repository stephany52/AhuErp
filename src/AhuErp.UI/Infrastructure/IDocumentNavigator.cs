namespace AhuErp.UI.Infrastructure
{
    /// <summary>
    /// Кросс-VM мост для навигации к карточке документа из любого экрана:
    /// «Мой рабочий стол», уведомления, журналы и т.п. Реализация в UI-слое
    /// переключает <see cref="ViewModels.MainViewModel"/> на вкладку РКК и
    /// выбирает документ по идентификатору.
    /// </summary>
    public interface IDocumentNavigator
    {
        /// <summary>
        /// Переключиться на раздел РКК и открыть документ с указанным
        /// идентификатором. Если документ не найден или не доступен текущей
        /// роли — никаких действий не выполняется.
        /// </summary>
        void OpenDocument(int documentId);
    }
}
