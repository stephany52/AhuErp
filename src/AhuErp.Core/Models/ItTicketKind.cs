namespace AhuErp.Core.Models
{
    /// <summary>
    /// Категория ИТ-заявки в Help Desk. Сопоставление с должностной
    /// инструкцией системного администратора МКУ «АХУ» БМР (info.txt):
    /// мелкий ремонт техники, диагностика и передача в сервис, установка
    /// и настройка ПО, сопровождение, проведение и настройка ВКС,
    /// администрирование сайта администрации района, настройка сети.
    /// </summary>
    /// <remarks>
    /// Целочисленные значения зафиксированы — менять нельзя, чтобы не
    /// сломать сохранённые значения в БД. Значение по умолчанию
    /// (<see cref="HardwareRepair"/>) — самый частый профиль обращений
    /// в учреждении.
    /// </remarks>
    public enum ItTicketKind
    {
        /// <summary>Ремонт / замена аппаратной части.</summary>
        HardwareRepair = 0,

        /// <summary>Установка/настройка ПО, обновления.</summary>
        SoftwareInstall = 1,

        /// <summary>Настройка локальной сети, VLAN, маршрутизации.</summary>
        NetworkConfig = 2,

        /// <summary>Подготовка и проведение видеоконференции.</summary>
        VideoConference = 3,

        /// <summary>Администрирование сайта администрации района.</summary>
        WebsiteAdmin = 4,

        /// <summary>Консультация пользователя.</summary>
        UserConsult = 5,

        /// <summary>Проведение диагностики без ремонта (передача в сервис).</summary>
        Diagnostic = 6,

        /// <summary>Прочая ИТ-задача, не подпадающая под перечисленные.</summary>
        Other = 99
    }
}
