namespace AhuErp.Core.Models
{
    /// <summary>
    /// Жизненный цикл акта о выделении к уничтожению архивных документов
    /// (Improvement #16 / Phase 19). Соответствует Приказу Росархива
    /// от 20.12.2019 № 236 (форма акта о выделении к уничтожению).
    /// </summary>
    public enum DestructionStatus
    {
        /// <summary>
        /// Проект акта: сформирован архивариусом, открыт для редактирования
        /// (можно добавлять/удалять дела). До утверждения ЭПК уничтожение
        /// не выполняется.
        /// </summary>
        Draft = 0,

        /// <summary>
        /// Акт утверждён руководителем (после согласования с ЭПК).
        /// Состав дел зафиксирован, изменения запрещены, но физического
        /// уничтожения ещё не произошло.
        /// </summary>
        Approved = 1,

        /// <summary>
        /// Документы уничтожены, дата фиксируется в <c>ExecutedAt</c>.
        /// Терминальный статус.
        /// </summary>
        Executed = 2,

        /// <summary>
        /// Акт отменён до утверждения / исполнения (например, дела
        /// продлены сроком хранения по результатам экспертизы).
        /// Терминальный статус.
        /// </summary>
        Cancelled = 3
    }
}
