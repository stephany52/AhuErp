namespace AhuErp.Core.Models
{
    /// <summary>
    /// Жизненный цикл документа в системе документооборота.
    /// Phase 13 — расширение под государственное делопроизводство.
    /// Переходы между статусами регулируются <see cref="Services.DocumentStateMachine"/>:
    /// произвольная смена запрещена, каждое изменение пишется в журнал аудита.
    /// </summary>
    /// <remarks>
    /// Целочисленные значения зафиксированы — менять нельзя, чтобы не сломать
    /// сохранённые значения в БД. Phase 1-12 знают только <see cref="New"/>,
    /// <see cref="InProgress"/>, <see cref="OnHold"/>, <see cref="Completed"/>,
    /// <see cref="Cancelled"/>, <see cref="Registered"/>; новые значения 6..12
    /// добавлены в Phase 13. <see cref="New"/> теперь трактуется как «Черновик»
    /// (Draft) — это начальное состояние любого нового документа.
    /// </remarks>
    public enum DocumentStatus
    {
        /// <summary>Черновик — документ создан, но ещё не зарегистрирован.</summary>
        New = 0,

        /// <summary>
        /// Legacy. До Phase 13 использовалось как «в работе». В новых местах
        /// рекомендуется <see cref="OnExecution"/>; во время чтения трактуется
        /// как синоним.
        /// </summary>
        InProgress = 1,

        /// <summary>Приостановлен (исполнитель ждёт прояснения / ресурс).</summary>
        OnHold = 2,

        /// <summary>Исполнен — работа по документу завершена.</summary>
        Completed = 3,

        /// <summary>Отменён — терминальный статус, документ вывели из работы.</summary>
        Cancelled = 4,

        /// <summary>Зарегистрирован — документу присвоен рег. номер по номенклатуре.</summary>
        Registered = 5,

        // ----- Phase 13 -----------------------------------------------------

        /// <summary>На согласовании — запущен маршрут согласования.</summary>
        OnApproval = 6,

        /// <summary>Согласован — все этапы маршрута дали Approved/Comments.</summary>
        Approved = 7,

        /// <summary>Отклонён — один из согласующих вернул на доработку.</summary>
        Rejected = 8,

        /// <summary>На подписании — документ передан подписанту (КЭП/НЭП/ПЭП).</summary>
        OnSigning = 9,

        /// <summary>Подписан — поставлена квалифицированная или иная подпись.</summary>
        Signed = 10,

        /// <summary>На исполнении — документ передан исполнителю под контроль срока.</summary>
        OnExecution = 11,

        /// <summary>Передан в архив — дело закрыто, доступ только архивисту.</summary>
        Archived = 12
    }
}
