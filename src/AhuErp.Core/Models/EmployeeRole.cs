namespace AhuErp.Core.Models
{
    /// <summary>
    /// Роль сотрудника, используется для контроля доступа к подсистемам ERP/EDMS.
    /// Целочисленные значения зафиксированы — менять нельзя, чтобы не сломать
    /// сохранённые значения в БД и сериализацию между релизами.
    /// </summary>
    public enum EmployeeRole
    {
        /// <summary>Системный администратор — полный доступ, включая админ-панель.</summary>
        Admin = 0,

        /// <summary>Руководитель учреждения или службы — полный функциональный доступ
        /// без админ-панели; редактирование оргструктуры/замещений ограничено
        /// собственным подразделением.</summary>
        Manager = 1,

        /// <summary>Сотрудник архивного отдела — работает с архивными запросами,
        /// номенклатурой дел, передачей дел в архив и архивными отчётами.</summary>
        Archivist = 2,

        /// <summary>Специалист службы по информационно-техническому обеспечению (ИТО).
        /// Видит РКК и журналы регистрации, обрабатывает ИТ-заявки и служебные
        /// записки, в которых он автор/исполнитель/согласующий, имеет узкий
        /// доступ к складу (только списания по ИТ-заявкам).</summary>
        TechSupport = 3,

        /// <summary>Ответственный за ТМЦ, транспортные заявки и хозяйственные
        /// операции. Видит склад, транспорт, журналы и поиск.</summary>
        WarehouseManager = 4,

        /// <summary>Делопроизводитель (Отдел делопроизводства / Общий отдел).
        /// Регистрирует входящие/исходящие, ведёт номенклатуру дел, готовит
        /// дела к передаче в архив. Без доступа к ТМЦ, транспорту и ИТО.</summary>
        Clerk = 5,

        /// <summary>Сотрудник отдела учёта/отчётности/кадрового обеспечения.
        /// Управляет оргструктурой и замещениями. К документам общий доступ
        /// не имеет — только к своим (автор / исполнитель / согласующий).</summary>
        HRAdmin = 6,

        /// <summary>Заместитель руководителя — то же, что <see cref="Manager"/>,
        /// но без админ-панели. Сейчас матрица идентична <see cref="Manager"/>;
        /// разделение оставлено на случай, если потребуется ужесточить
        /// поведенческие предикаты (например, ограничить редактирование шаблонов).</summary>
        DeputyHead = 7,

        /// <summary>Ответственный за автопарк (опциональная роль). Если в учреждении
        /// автопарк и ТМЦ ведут разные люди, эта роль даёт доступ к транспорту,
        /// поиску и журналам без склада.</summary>
        FleetManager = 8
    }
}
