namespace AhuErp.Core.Models
{
    /// <summary>
    /// Тип документа, выдаваемого по архивному запросу (Improvement #16 / Phase 19).
    /// Соответствует п. 5.10 «Правил организации хранения, комплектования, учёта
    /// и использования документов Архивного фонда Российской Федерации»
    /// (Приказ Минкультуры от 31.03.2015 № 526).
    /// </summary>
    public enum ArchiveResponseKind
    {
        /// <summary>
        /// Архивная справка — официальное письмо, содержащее сведения о
        /// предмете запроса со ссылками на номера дел, листы и даты.
        /// </summary>
        Spravka = 0,

        /// <summary>
        /// Архивная выписка — дословное воспроизведение части документа,
        /// относящейся к предмету запроса, с заголовком, реквизитами и
        /// заверительной надписью.
        /// </summary>
        Vypiska = 1,

        /// <summary>
        /// Архивная копия — дословное воспроизведение документа целиком
        /// с заверительной надписью архива.
        /// </summary>
        Kopiya = 2
    }
}
